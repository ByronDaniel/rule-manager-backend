import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createServer } from 'node:net';
import argon2 from 'argon2';
import request from 'supertest';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { connectMongo } from '../src/infrastructure/mongo.js';
import { createApp } from '../src/app.js';

test('HTTP maker-checker flow, security, and idempotency', async () => {
  const replica = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  const store = await connectMongo(replica.getUri(), 'test');
  try {
    const config = { jwtSecret: 'test-secret-that-is-long-enough-for-tests', jwtIssuer: 'test', jwtAudience: 'test', jwtExpiresIn: 3600, corsOrigin: false };
    const app = createApp(store, config);
    for (const [username, roles] of [['maker', ['MAKER']], ['checker', ['CHECKER']], ['consumer', ['CONSUMER']], ['auditor', ['AUDITOR']], ['both', ['MAKER', 'CHECKER']], ['system', ['MAKER']]]) await store.repo('users').insert({ username, roles, passwordHash: await argon2.hash('a-long-test-password') });
    const login = async username => {
      const response = await request(app).post('/api/v1/auth/token').send({ username, password: 'a-long-test-password' });
      assert.equal(response.status, 200, JSON.stringify(response.body));
      return `Bearer ${response.body.accessToken}`;
    };
    const maker = await login('maker');
    const checker = await login('checker');
    const consumer = await login('consumer');
    const auditor = await login('auditor');
    const both = await login('both');
    assert.equal((await request(app).post('/api/v1/auth/token').send({ username: 'unknown', password: 'wrong' })).status, 401);
    const key = randomUUID();
    const parameterBody = { code: 'TEST_LIMIT', name: 'Test limit', category: 'LIMITS', businessDomain: 'PAYMENTS', dataType: 'MONEY' };
    const create = () => request(app).post('/api/v1/parameters').set('Authorization', maker).set('Idempotency-Key', key).send(parameterBody);
    const parameter = await create();
    assert.equal(parameter.status, 201, JSON.stringify(parameter.body));
    const draftList = await request(app).get('/api/v1/parameters').set('Authorization', maker);
    assert.equal(draftList.body.items.length, 1);
    assert.equal(Object.hasOwn(draftList.body.items[0], 'currentValue'), false);
    const replay = await create();
    assert.equal(replay.body.id, parameter.body.id);
    const reused = await request(app).post('/api/v1/parameters').set('Authorization', maker).set('Idempotency-Key', key).send({ ...parameterBody, code: 'OTHER_CODE' });
    assert.equal(reused.status, 422);
    assert.equal(reused.body.businessCode, 'IDEMPOTENCY_KEY_REUSED');
    const missingMatch = await request(app).put(`/api/v1/parameters/${parameter.body.id}`).set('Authorization', maker).send({ name: 'Updated name', category: 'LIMITS', businessDomain: 'PAYMENTS' });
    assert.equal(missingMatch.status, 428);
    const proposed = await request(app).post('/api/v1/change-requests').set('Authorization', maker).set('Idempotency-Key', randomUUID()).send({ parameterId: parameter.body.id, changeType: 'SET_VALUE', proposedValue: '100.00', reason: 'Initial value' });
    assert.equal(proposed.status, 201, JSON.stringify(proposed.body));
    assert.equal((await request(app).get('/api/v1/change-requests').set('Authorization', checker)).body.items.length, 1);
    assert.equal((await request(app).get(`/api/v1/change-requests/${proposed.body.id}`).set('Authorization', maker)).status, 200);
    const approve = await request(app).post(`/api/v1/change-requests/${proposed.body.id}/approval`).set('Authorization', checker).set('If-Match', proposed.headers.etag).set('Idempotency-Key', randomUUID()).send({});
    assert.equal(approve.status, 201, JSON.stringify(approve.body));
    assert.equal((await request(app).get(`/api/v1/change-requests/${proposed.body.id}/approval`).set('Authorization', maker)).status, 200);
    assert.equal((await request(app).get(`/api/v1/change-requests/${proposed.body.id}/rejection`).set('Authorization', maker)).status, 404);
    const current = await request(app).get('/api/v1/parameter-values/TEST_LIMIT').set('Authorization', consumer);
    assert.equal(current.status, 200, JSON.stringify(current.body));
    assert.equal(current.body.value, '100.00');
    const scoped = await request(app).get('/api/v1/parameter-values').set('Authorization', consumer).query({ channel: 'MOBILE', product: 'CREDIT_CARD' });
    assert.equal(scoped.status, 200);
    assert.equal(scoped.body.items[0].code, 'TEST_LIMIT');
    assert.equal((await request(app).get('/api/v1/parameter-values/TEST_LIMIT').set('Authorization', consumer).set('If-None-Match', current.headers.etag)).status, 304);
    assert.equal((await request(app).get('/api/v1/parameter-values').set('Authorization', consumer).query({ codes: 'TEST_LIMIT,NO_SUCH_CODE' })).body.unavailable[0].reason, 'NOT_FOUND');
    assert.equal((await request(app).get('/api/v1/audit-events')).status, 401);
    assert.equal((await request(app).get('/api/v1/audit-events').set('Authorization', maker).query({ from: '2020-01-01T00:00:00Z' })).status, 403);
    const audit = await request(app).get('/api/v1/audit-events').set('Authorization', auditor).query({ parameterId: parameter.body.id });
    assert.equal(audit.status, 200);
    assert.equal((await request(app).get(`/api/v1/audit-events/${audit.body.items[0].id}`).set('Authorization', auditor)).status, 200);
    const scheduled = await request(app).post('/api/v1/change-requests').set('Authorization', maker).set('Idempotency-Key', randomUUID()).send({ parameterId: parameter.body.id, changeType: 'SET_VALUE', proposedValue: '200.00', baseVersionNumber: 1, effectiveFrom: '2099-01-01T00:00:00Z', reason: 'Scheduled value' });
    assert.equal(scheduled.status, 201, JSON.stringify(scheduled.body));
    const scheduledDecision = await request(app).post(`/api/v1/change-requests/${scheduled.body.id}/approval`).set('Authorization', checker).set('If-Match', scheduled.headers.etag).set('Idempotency-Key', randomUUID()).send({});
    assert.equal(scheduledDecision.status, 201, JSON.stringify(scheduledDecision.body));
    assert.equal(scheduledDecision.body.publicationStatus, 'SCHEDULED');
    assert.equal((await request(app).get('/api/v1/parameter-values/TEST_LIMIT').set('Authorization', consumer)).body.value, '100.00');
    await store.repo('versions').update({ parameterId: parameter.body.id, versionNumber: 1 }, { $set: { effectiveFrom: '2024-01-01T00:00:00.000Z' } });
    await store.repo('versions').update({ parameterId: parameter.body.id, versionNumber: 2 }, { $set: { effectiveFrom: '2025-01-01T00:00:00.000Z' } });
    assert.equal((await request(app).get('/api/v1/parameter-values/TEST_LIMIT').set('Authorization', consumer)).body.value, '200.00');
    const updated = await request(app).get(`/api/v1/parameters/${parameter.body.id}`).set('Authorization', maker);
    assert.equal(updated.body.currentVersionNumber, 2);
    assert.equal(Object.hasOwn(updated.body, 'currentValue'), false);
    const listed = await request(app).get('/api/v1/parameters').set('Authorization', maker).query({ code: 'TEST_LIMIT' });
    assert.equal(listed.body.items[0].currentValue, '200.00');
    const history = await request(app).get(`/api/v1/parameters/${parameter.body.id}/versions`).set('Authorization', auditor);
    assert.equal(history.status, 200, JSON.stringify(history.body));
    assert.deepEqual(history.body.items.map(version => [version.versionNumber, version.status, version.value]), [[2, 'ACTIVE', '200.00'], [1, 'EXPIRED', '100.00']]);
    assert.equal(history.body.page.totalElements, 2);
    assert.equal((await request(app).get(`/api/v1/parameters/${parameter.body.id}/versions`).set('Authorization', consumer)).status, 403);
    assert.equal((await request(app).get(`/api/v1/parameters/${randomUUID()}/versions`).set('Authorization', maker)).status, 404);
    const events = await store.repo('audit').find({ parameterId: parameter.body.id, operation: 'VERSION_ACTIVATED' });
    assert.equal(events.length, 1);
    assert.equal(events[0].actor.type, 'SYSTEM');
    const namedSystem = await login('system');
    const systemParameter = await request(app).post('/api/v1/parameters').set('Authorization', namedSystem).set('Idempotency-Key', randomUUID()).send({ ...parameterBody, code: 'SYSTEM_LIMIT' });
    assert.equal(systemParameter.status, 201);
    const systemUserEvent = await store.repo('audit').findOne({ parameterId: systemParameter.body.id, operation: 'PARAMETER_CREATED' });
    assert.equal(systemUserEvent.actor.type, 'USER');
    const makeConcurrentProposal = value => request(app).post('/api/v1/change-requests').set('Authorization', maker).set('Idempotency-Key', randomUUID()).send({ parameterId: parameter.body.id, changeType: 'SET_VALUE', proposedValue: value, baseVersionNumber: 2, reason: 'Concurrent update' });
    const proposals = await Promise.all([makeConcurrentProposal('300'), makeConcurrentProposal('400')]);
    assert.deepEqual(proposals.map(response => response.status), [201, 201]);
    const decisions = await Promise.all(proposals.map(proposal => request(app).post(`/api/v1/change-requests/${proposal.body.id}/approval`).set('Authorization', checker).set('If-Match', proposal.headers.etag).set('Idempotency-Key', randomUUID()).send({})));
    assert.deepEqual(decisions.map(response => response.status).sort(), [201, 409]);
    assert.equal(decisions.find(response => response.status === 409).body.businessCode, 'BASE_VERSION_MISMATCH');
    const other = await request(app).post('/api/v1/parameters').set('Authorization', both).set('Idempotency-Key', randomUUID()).send({ ...parameterBody, code: 'OTHER_LIMIT' });
    const ownRequest = await request(app).post('/api/v1/change-requests').set('Authorization', both).set('Idempotency-Key', randomUUID()).send({ parameterId: other.body.id, changeType: 'SET_VALUE', proposedValue: '5', reason: 'Own proposal' });
    const ownDecision = await request(app).post(`/api/v1/change-requests/${ownRequest.body.id}/approval`).set('Authorization', both).set('If-Match', ownRequest.headers.etag).set('Idempotency-Key', randomUUID()).send({});
    assert.equal(ownDecision.status, 403);
    assert.equal(ownDecision.body.businessCode, 'MAKER_CHECKER_VIOLATION');
    const reject = await request(app).post(`/api/v1/change-requests/${ownRequest.body.id}/rejection`).set('Authorization', checker).set('If-Match', ownRequest.headers.etag).set('Idempotency-Key', randomUUID()).send({ reason: 'This proposal needs revision.' });
    assert.equal(reject.status, 201, JSON.stringify(reject.body));
    assert.equal((await request(app).get(`/api/v1/change-requests/${ownRequest.body.id}/rejection`).set('Authorization', both)).status, 200);
    const editable = await request(app).get(`/api/v1/parameters/${other.body.id}`).set('Authorization', both);
    const modified = await request(app).put(`/api/v1/parameters/${other.body.id}`).set('Authorization', both).set('If-Match', editable.headers.etag).send({ name: 'Updated name', category: 'LIMITS', businessDomain: 'PAYMENTS' });
    assert.equal(modified.status, 200, JSON.stringify(modified.body));
    assert.equal((await request(app).delete(`/api/v1/parameters/${other.body.id}`).set('Authorization', both).set('If-Match', editable.headers.etag)).status, 412);
    assert.equal((await request(app).delete(`/api/v1/parameters/${other.body.id}`).set('Authorization', both).set('If-Match', modified.headers.etag)).status, 204);
    const retired = await request(app).get('/api/v1/parameter-values/OTHER_LIMIT').set('Authorization', consumer);
    assert.equal(retired.status, 404);
    assert.equal(retired.body.businessCode, 'PARAMETER_INACTIVE');
    const futureParameter = await request(app).post('/api/v1/parameters').set('Authorization', maker).set('Idempotency-Key', randomUUID()).send({ ...parameterBody, code: 'FUTURE_LIMIT' });
    const futureProposal = await request(app).post('/api/v1/change-requests').set('Authorization', maker).set('Idempotency-Key', randomUUID()).send({ parameterId: futureParameter.body.id, changeType: 'SET_VALUE', proposedValue: '10', effectiveFrom: '2099-01-01T00:00:00Z', reason: 'Future publication' });
    const futureApproval = await request(app).post(`/api/v1/change-requests/${futureProposal.body.id}/approval`).set('Authorization', checker).set('If-Match', futureProposal.headers.etag).set('Idempotency-Key', randomUUID()).send({});
    assert.equal(futureApproval.body.publicationStatus, 'SCHEDULED');
    const futureDetail = await request(app).get(`/api/v1/parameters/${futureParameter.body.id}`).set('Authorization', maker);
    assert.equal(futureDetail.body.status, 'DRAFT');
    const futureRetire = await request(app).delete(`/api/v1/parameters/${futureParameter.body.id}`).set('Authorization', maker).set('If-Match', futureDetail.headers.etag);
    assert.equal(futureRetire.status, 409);
    assert.equal(futureRetire.body.businessCode, 'PARAMETER_PUBLISHED');
    const occupied = createServer();
    await new Promise(resolve => occupied.listen(0, resolve));
    try {
      const child = spawn(process.execPath, ['src/server.js'], { env: { ...process.env, MONGODB_URI: replica.getUri(), MONGODB_DATABASE: 'test', JWT_SECRET: config.jwtSecret, PORT: String(occupied.address().port) }, stdio: ['ignore', 'pipe', 'pipe'] });
      const childTimeout = setTimeout(() => child.kill('SIGKILL'), 10000);
      let output = '';
      child.stdout.on('data', chunk => { output += chunk; });
      child.stderr.on('data', chunk => { output += chunk; });
      const [exitCode] = await once(child, 'close');
      clearTimeout(childTimeout);
      assert.equal(exitCode, 1);
      assert.match(output, /EADDRINUSE/);
      assert.doesNotMatch(output, /RMA listening/);
    } finally { await new Promise(resolve => occupied.close(resolve)); }
  } finally { await store.client.close(); await replica.stop(); }
});